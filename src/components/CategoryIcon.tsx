export const getSubcategoryIconName = (name: string, fallback = 'Tag'): string => {
  try {
    const custom = JSON.parse(localStorage.getItem('et_subcat_icons') || '{}');
    if (custom[name] && ICON_MAP[custom[name]]) return custom[name];
  } catch {
    /* ignore */
  }
  for (const [re, icon] of KEYWORDS) if (re.test(name) && ICON_MAP[icon]) return icon;
  return fallback;
};

export const setCustomSubcategoryIcon = (name: string, icon: string) => {
  try {
    const custom = JSON.parse(localStorage.getItem('et_subcat_icons') || '{}');
    custom[name] = icon;
    localStorage.setItem('et_subcat_icons', JSON.stringify(custom));
  } catch {
    /* ignore */
  }
};
